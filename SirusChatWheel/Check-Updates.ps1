param([string]$Repository = '', [switch]$PromptForRepository, [switch]$Quiet)
$ErrorActionPreference = 'Stop'
$configPath = Join-Path $PSScriptRoot 'UpdateConfig.json'
$statusPath = Join-Path $PSScriptRoot 'UpdateStatus.lua'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Write-Status([string]$RepoName, [string]$ReleaseVersion, [string]$State) {
    # Values have been restricted to ASCII identifiers and known state names.
    # Never execute code or write unvalidated release text returned by GitHub.
    $checkedAt = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
    $url = if ($RepoName) { 'https://github.com/' + $RepoName + '/releases/latest' } else { '' }
    $content = '-- Generated by Check-Updates.ps1.' + "`n" +
        'SirusChatWheelUpdateStatus = { repository = "' + $RepoName +
        '", version = "' + $ReleaseVersion + '", state = "' + $State +
        '", checkedAt = ' + $checkedAt + ', url = "' + $url + '" }' + "`n"
    $temporary = $statusPath + '.tmp'
    [IO.File]::WriteAllText($temporary, $content, $utf8)
    if (Test-Path -LiteralPath $statusPath) { [IO.File]::Replace($temporary, $statusPath, [NullString]::Value) }
    else { [IO.File]::Move($temporary, $statusPath) }
}

try {
    $explicitRepository = -not [string]::IsNullOrWhiteSpace($Repository)
    if (-not $explicitRepository -and (Test-Path -LiteralPath $configPath)) {
        $config = Get-Content -LiteralPath $configPath -Raw -Encoding UTF8 | ConvertFrom-Json
        $Repository = [string]$config.repository
    }
    if ([string]::IsNullOrWhiteSpace($Repository) -and $PromptForRepository) {
        $Repository = Read-Host 'GitHub repository URL or OWNER/REPO (public repository)'
        $explicitRepository = -not [string]::IsNullOrWhiteSpace($Repository)
    }
    if ([string]::IsNullOrWhiteSpace($Repository)) {
        if (-not (Test-Path -LiteralPath $statusPath)) { Write-Status '' '' 'unconfigured' }
        if (-not $Quiet) { Write-Host 'Run Check-Updates.cmd once to configure a public GitHub repository.' }
        exit 0
    }
    $Repository = $Repository.Trim().TrimEnd('/')
    $Repository = $Repository -replace '^https://github\.com/', '' -replace '\.git$', ''
    if ($Repository -notmatch '^[A-Za-z0-9][A-Za-z0-9-]{0,38}/[A-Za-z0-9_.-]{1,100}$' -or
        ($Repository.Split('/')[1] -in @('.', '..'))) {
        throw 'Use a GitHub repository URL or OWNER/REPO; other hosts and paths are not supported.'
    }
    if ($explicitRepository) {
        $json = @{ repository = $Repository } | ConvertTo-Json
        [IO.File]::WriteAllText($configPath, $json + "`n", $utf8)
    }
    $toc = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'SirusChatWheel.toc') -Encoding UTF8
    $versionLine = $toc | Where-Object { $_ -match '^## Version:\s*(\d+\.\d+\.\d+)\s*$' } | Select-Object -First 1
    if (-not $versionLine -or $versionLine -notmatch '^## Version:\s*(\d+\.\d+\.\d+)\s*$') {
        throw 'Could not read the installed version from SirusChatWheel.toc.'
    }
    $installed = $Matches[1]
    [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
    $headers = @{ Accept = 'application/vnd.github+json'; 'X-GitHub-Api-Version' = '2026-03-10' }
    $release = Invoke-RestMethod -Uri ('https://api.github.com/repos/' + $Repository + '/releases/latest') `
        -Headers $headers -UserAgent ('SirusChatWheel/' + $installed) -TimeoutSec 8
    if ($release.draft -eq $true -or $release.prerelease -eq $true -or
        [string]$release.tag_name -cnotmatch '^v?(\d{1,5}\.\d{1,5}\.\d{1,5})$') {
        throw 'The latest stable release must have a tag such as v1.2.4.'
    }
    $latest = $Matches[1]
    $newer = [version]$latest -gt [version]$installed
    Write-Status $Repository $latest 'ok'
    if (-not $Quiet -or $newer) {
        Write-Host ('Installed: ' + $installed + '; GitHub: ' + $latest)
        if ($newer) {
            Write-Host ('Update available: https://github.com/' + $Repository + '/releases/latest')
            Write-Host 'Use the -update.zip asset to preserve your sounds and catalog.'
        } else { Write-Host 'No newer stable release.' }
        Write-Host 'Use /reload in game, then /scw update to see this check.'
    }
} catch {
    # A failed check is not evidence that the installed version is current.
    $safeRepository = ''
    if ($Repository -match '^[A-Za-z0-9][A-Za-z0-9-]{0,38}/[A-Za-z0-9_.-]{1,100}$' -and
        ($Repository.Split('/')[1] -notin @('.', '..'))) { $safeRepository = $Repository }
    try { Write-Status $safeRepository '' 'failed' } catch { }
    if (-not $Quiet) { Write-Warning ('Update check failed: ' + $_.Exception.Message) }
    exit 1
}
