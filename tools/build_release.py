"""Build installation/update/source ZIPs from a source checkout on Windows."""
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ADDON = ROOT / "SirusChatWheel"
DIST = ROOT / "dist"
FILES = ["Bindings.xml", "Core.lua", "Init.lua", "Sounds.lua", "Wheel.lua", "Options.lua", "Updates.lua",
    "SirusChatWheel.toc", "SoundCatalog.ps1", "Check-Updates.ps1", "Check-Updates.cmd", "Update-Sounds.cmd",
    "Watch-Sounds.cmd", "Start-ChatWheel.cmd", "README_RU.txt", "TEST_REPORT_RU.txt", "SoundNames.example.json"]
SAMPLES = ["Cat.wav", "Dog.wav"]


def user_data(rel):
    return rel in {"Catalog.lua", "SoundNames.json", "UpdateConfig.json"} or rel.startswith(("Sounds/", "Media/Cache/"))


def source_files():
    for name in FILES:
        yield ADDON / name
    for name in SAMPLES:
        yield ADDON / "Sounds" / name
    yield from sorted(p for p in (ADDON / "Media").iterdir() if p.suffix.lower() in {".tga", ".blp"})


def build():
    version = re.search(r"^## Version:\s*(\d+\.\d+\.\d+)\s*$", (ADDON / "SirusChatWheel.toc").read_text(encoding="utf-8-sig"), re.M).group(1)
    assert f'A.version = "{version}"' in (ADDON / "Core.lua").read_text(encoding="utf-8")
    DIST.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="scw-release-") as folder:
        stage = Path(folder) / "SirusChatWheel"
        for file in source_files():
            target = stage / file.relative_to(ADDON)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(file, target)
        (stage / "UpdateStatus.lua").write_text("-- Generated by Check-Updates.ps1.\nSirusChatWheelUpdateStatus = {}\n", encoding="utf-8")
        names = json.loads((stage / "SoundNames.example.json").read_text(encoding="utf-8-sig"))
        (stage / "SoundNames.json").write_text(json.dumps(names, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        ps = Path(os.environ["SystemRoot"]) / "System32/WindowsPowerShell/v1.0/powershell.exe"
        env = os.environ.copy()
        env["PSModulePath"] = str(ps.parent / "Modules")
        subprocess.run([str(ps), "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(stage / "SoundCatalog.ps1")], check=True, env=env)
        for update in (False, True):
            path = DIST / (f"SirusChatWheel-{version}" + ("-update" if update else "") + ".zip")
            with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
                for file in sorted(stage.rglob("*")):
                    if file.is_file() and not (update and user_data(file.relative_to(stage).as_posix())):
                        archive.write(file, "SirusChatWheel/" + file.relative_to(stage).as_posix())
            print(path)
    # This source snapshot uses an explicit list: local names, config and custom
    # sounds are excluded even when the working installation contains them.
    path = DIST / f"SirusChatWheel-{version}-source.zip"
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        files = list(source_files()) + [ROOT / name for name in [".gitignore", "README_GITHUB_RU.md", "tools/build_release.py", "tests/validate.py", "tests/wow_mock.lua"]]
        for file in files:
            archive.write(file, file.relative_to(ROOT).as_posix())
    print(path)


if __name__ == "__main__":
    build()
