"""Build one complete playable ZIP with a single copy of each sound."""
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ADDON = ROOT / "SirusChatWheel"
DIST = ROOT / "dist"
FILES = ["Bindings.xml", "Core.lua", "Init.lua", "Players.lua", "Sounds.lua", "Wheel.lua", "Options.lua", "Updates.lua",
    "SirusChatWheel.toc", "SoundCatalog.ps1", "Check-Updates.ps1", "Check-Updates.cmd", "Update-Sounds.cmd",
    "Watch-Sounds.cmd", "Start-ChatWheel.cmd", "README_RU.txt", "TEST_REPORT_RU.txt", "SoundNames.json"]
AUTHOR_ONLY = {"SoundNames.json", "Update-Sounds.cmd", "Watch-Sounds.cmd"}


def source_files():
    for name in FILES:
        yield ADDON / name
    yield from sorted(p for p in (ADDON / "Sounds").rglob("*") if p.is_file() and p.suffix.lower() in {".wav", ".mp3", ".ogg"})
    yield from sorted(p for p in (ADDON / "Media").iterdir() if p.suffix.lower() in {".tga", ".blp"})


def build():
    version = re.search(r"^## Version:\s*(\d+\.\d+\.\d+)\s*$", (ADDON / "SirusChatWheel.toc").read_text(encoding="utf-8-sig"), re.M).group(1)
    assert f'A.version = "{version}"' in (ADDON / "Core.lua").read_text(encoding="utf-8")
    names = json.loads((ADDON / "SoundNames.json").read_text(encoding="utf-8-sig"))
    if not isinstance(names, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in names.items()):
        raise ValueError("SoundNames.json must contain file-name to display-name strings")
    DIST.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="scw-release-") as folder:
        stage = Path(folder) / "SirusChatWheel"
        for file in source_files():
            target = stage / file.relative_to(ADDON)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(file, target)
        (stage / "UpdateStatus.lua").write_text("-- Generated by Check-Updates.ps1.\nSirusChatWheelUpdateStatus = {}\n", encoding="utf-8")
        ps = Path(os.environ["SystemRoot"]) / "System32/WindowsPowerShell/v1.0/powershell.exe"
        env = os.environ.copy()
        env["PSModulePath"] = str(ps.parent / "Modules")
        subprocess.run([str(ps), "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(stage / "SoundCatalog.ps1")], check=True, env=env)
        audio_count = sum(1 for p in (stage / "Sounds").rglob("*") if p.is_file())
        catalog = (stage / "Catalog.lua").read_text(encoding="utf-8-sig")
        if catalog.count('  { id = ') != audio_count:
            raise RuntimeError("Some sound files were not added to the release catalog")
        (stage / "ReleaseInfo.json").write_text(json.dumps({"version": version, "readyCatalog": True}) + "\n", encoding="utf-8")
        path = DIST / f"SirusChatWheel-{version}.zip"
        with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
            for file in sorted(stage.rglob("*")):
                if file.is_file():
                    relative = file.relative_to(stage)
                    if relative.parts[0] == "Sounds" or relative.as_posix() in AUTHOR_ONLY:
                        continue
                    archive.write(file, "SirusChatWheel/" + relative.as_posix())
        print(path)
    return path


if __name__ == "__main__":
    build()
